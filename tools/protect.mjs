// Build step: web-src/ -> android/app/src/main/assets/www (minified JS, every file AES-256-GCM encrypted)
// and a generated K.java holding the key (split + masked; R8 obfuscates the class further).
// Format of each output file: 12-byte IV | ciphertext | 16-byte tag (the layout javax.crypto GCM expects).
import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, statSync } from 'node:fs';
import { join, relative, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'web-src'), out = join(root, 'android/app/src/main/assets/www');
const keyFile = join(root, 'android/web.key');   // kept between builds so the same key encrypts every release; keep private
let key;
try { key = readFileSync(keyFile); } catch { key = randomBytes(32); writeFileSync(keyFile, key); }

const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const minify = (code) => execFileSync('npx', ['--yes', 'esbuild@0.24.0', '--minify', '--format=esm', '--charset=utf8', '--legal-comments=none'], { input: code, maxBuffer: 1 << 28 });

rmSync(out, { recursive: true, force: true });
let n = 0;
for (const f of walk(src)) {
  const rel = relative(src, f);
  let data = readFileSync(f);
  if (extname(f) === '.js' && !rel.startsWith('lib/')) data = minify(data);   // third-party lib/ is already built code
  const iv = randomBytes(12), c = createCipheriv('aes-256-gcm', key, iv);
  const enc = Buffer.concat([iv, c.update(data), c.final(), c.getAuthTag()]);
  const dst = join(out, rel); mkdirSync(dirname(dst), { recursive: true }); writeFileSync(dst, enc);
  // round-trip check, so a bad build fails here instead of on a phone
  const d = createDecipheriv('aes-256-gcm', key, enc.subarray(0, 12)); d.setAuthTag(enc.subarray(enc.length - 16));
  if (Buffer.compare(Buffer.concat([d.update(enc.subarray(12, enc.length - 16)), d.final()]), data)) throw new Error('round trip failed: ' + rel);
  n++;
}

// key = mask XOR blob, in four chunks, so no 32-byte constant sits in the dex
const mask = randomBytes(32), blob = Buffer.from(key.map((b, i) => b ^ mask[i]));
const arr = (b) => '{' + [...b].map((x) => (x > 127 ? x - 256 : x)).join(',') + '}';
writeFileSync(join(root, 'android/app/src/main/java/com/kaniyan/app/K.java'),
  `package com.kaniyan.app;\n\n/** Generated by tools/protect.mjs. Do not edit or commit. */\nfinal class K {\n    private static final byte[] A = ${arr(mask)};\n    private static final byte[] B = ${arr(blob)};\n\n    static byte[] get() {\n        byte[] k = new byte[32];\n        for (int i = 0; i < 32; i++) k[i] = (byte) (A[i] ^ B[i]);\n        return k;\n    }\n}\n`);
console.log(`protected ${n} files`);
